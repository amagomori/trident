fn encode(intensity: f64, curve: &[f64]) -> u8 {
    if intensity <= 0.0 {
        return 0;
    }
    let hi = curve.partition_point(|&sample| sample < intensity);
    let high_code = 255 - 5 * (curve.len() - 1 - hi) as u16;
    let width = if hi == 1 { 1 } else { 5 };
    let fraction = (intensity - curve[hi - 1]) / (curve[hi] - curve[hi - 1]);
    // Xcms truncates the interpolated 16-bit value before rounding to 8 bits.
    let value = (high_code - width) * 257 + (fraction * f64::from(width * 257)) as u16;
    ((u32::from(value) + 128) / 257) as u8
}

pub(super) fn encode_rgb([r, g, b]: [f64; 3]) -> crate::colors::Rgb {
    (encode(r, RED), encode(g, GREEN), encode(b, BLUE))
}
