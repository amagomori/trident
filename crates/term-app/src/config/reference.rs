//! Generates the user reference from the file schema and the settings of an empty config.

use super::*;
use std::fmt::Write;

trait TomlForm {
    fn form(&self) -> &'static str;
}

macro_rules! forms {
    ($($ty:ty => $form:literal),+ $(,)?) => {$(
        impl TomlForm for $ty {
            fn form(&self) -> &'static str { $form }
        }
    )+};
}

forms! {
    Option<bool> => "boolean",
    Option<String> => "string",
    OptionAsAlt => "string",
    Option<f32> => "number",
    Option<f64> => "number",
    Option<u64> => "integer",
    Option<usize> => "integer",
    Option<Scrollback> => "integer or table",
    Option<CompareRunsEntry> => "boolean or table",
    Option<Shell> => "string or array of strings",
    Option<theme::Selection> => "string or table",
    Vec<String> => "array of strings",
    BTreeMap<String, String> => "table of strings",
    BTreeMap<String, Binding> => "table of bindings",
}

fn literal(value: impl serde::Serialize) -> String {
    format!("`{}`", toml::Value::try_from(value).unwrap())
}

fn render() -> String {
    let c = parse(Path::new("config.toml"), "").unwrap();
    let mut doc = String::from(
        "# Configuration reference\n\n\
         <!-- Generated by config::reference. See development.md to regenerate. -->\n\n\
         Every entry in `config.toml` is optional. Defaults below apply before command-line overrides.\n\
         See the [configuration guide](configuration.md#config-file) for the file location and a working example.\n\n\
         ## Top-level settings\n",
    );

    // An exhaustive pattern makes adding or removing a schema field a compile-time check.
    macro_rules! table {
        ($schema:ident { $($key:ident: $default:expr => $meaning:expr),+ $(,)? }) => {{
            let $schema { $($key),+ } = $schema::default();
            doc.push_str("\n| Key | TOML type | Default | Effect |\n| --- | --- | --- | --- |\n");
            $(writeln!(doc, "| `{}` | {} | {} | {} |", stringify!($key), $key.form(), $default, $meaning).unwrap();)+
        }};
    }
    let tab_mode = TabBarMode::NAMES
        .iter()
        .find(|(_, mode)| *mode == c.tab_bar)
        .unwrap()
        .0;
    table!(Raw {
        app_icon: literal(c.app_icon.name()) => format!("Choose an [app icon](usage.md#app-icons): {}.", AppIcon::ALL.map(|icon| literal(icon.name())).join(", ")),
        auto_secure_input: literal(c.auto_secure_input) => "Enable Secure Keyboard Entry at password prompts on macOS.",
        clipboard_read: literal(c.clipboard_read) => "Allow programs to read the clipboard with OSC 52.",
        colors: "From the theme" => "Override individual [palette colors](#colors) in both light and dark themes.",
        compare_runs: literal(c.compare_runs) => "Mark output that changed since the previous run of the same command. See [compare_runs](#compare_runs).",
        confirm_close: literal(c.confirm_close) => "Confirm before closing a tab or window with a running program.",
        desktop_notifications: literal(c.desktop_notifications) => "Allow programs to request desktop notifications with OSC 9, 777 or 99.",
        drop_preview: literal(c.drop_preview) => "Show a preview when dropping a supported file. Disable to insert only its quoted path.",
        editor: "`$VISUAL`, then `$EDITOR`" => "Open [file links](usage.md#links) with this command. Use an array for arguments containing spaces.",
        env: literal(&c.env) => "Set environment variables for child processes, overriding inherited values.",
        font: "Bundled JetBrains Mono" => "Choose a font family or font file. See [Fonts](configuration.md#fonts).",
        font_bold: "From `font`" => "Override the bold face with a family name or file.",
        font_bold_italic: "From `font`" => "Override the bold italic face with a family name or file.",
        font_italic: "From `font`" => "Override the italic face with a family name or file.",
        font_size: literal(c.font_size) => "Set the font size in points, from 4 to 200.",
        hide_mouse_when_typing: literal(c.hide_mouse_when_typing) => "Hide the pointer while sending keyboard input. Moving the mouse shows it again.",
        hover_preview: literal(c.hover_preview) => "Preview a file path when holding Cmd (macOS) or Ctrl (Linux) over it.",
        keybindings: "[Platform shortcuts](usage.md#keyboard-and-mouse)" => "Map a chord to an action name or `{ send = \"text\" }`. Use `\"none\"` to unbind. See [Key bindings](configuration.md#key-bindings).",
        ligatures: literal(c.ligatures) => "Enable [programming ligatures](configuration.md#fonts) in fonts that support them.",
        menu_bar_icon: literal(c.menu_bar_icon) => "Show the Trident menu bar item on macOS.",
        notify_long_commands_after: literal(c.notify_long_commands_after) => "Notify when a command finishes in an unfocused tab after at least this many seconds. Set to 0 to disable.",
        option_as_alt: literal(c.option_as_alt) => "On macOS, use `\"left\"`, `\"right\"` or `\"both\"` to send Meta with the selected Option keys. Use `\"none\"` to keep native text entry on both. See [Key bindings](configuration.md#key-bindings).",
        padding: literal(c.padding) => "Set the space around the grid in logical pixels, from 0 to 1000.",
        pager: literal(&c.pager) => "Open the last command’s output with this program. Trident appends the output file path.",
        paste_protection: literal(c.paste_protection) => "Confirm a paste containing line breaks or control characters outside bracketed paste mode. See [Paste](usage.md#paste).",
        remember_window_size: literal(c.remember_window_size) => "Restore the last window size and maximized state unless a row or column count is set.",
        scrollback: literal(c.scrollback) => "Keep this many lines of history. Set to 0 to disable or use the [scrollback](#scrollback) table to limit each command.",
        shell: "Login shell" => "Start this program in the terminal. Use an array to pass arguments.",
        tab_bar: literal(tab_mode) => "On Linux, use `\"always\"`, `\"auto\"` (two or more tabs) or `\"never\"`. macOS uses native tabs.",
        term: literal(&c.term) => "Set `TERM` for child processes. A missing [terminfo entry](usage.md#terminfo) falls back to `xterm-256color`.",
        theme: "`\"tokyo-night\"`" => "Use a bundled name, a theme file, `\"auto\"` or a table with both `light` and `dark` names or paths. See [Color themes](configuration.md#color-themes).",
        trim_paste: literal(c.trim_paste) => "Remove trailing whitespace from a single-line paste, including its final newline.",
        visual_bell: literal(c.visual_bell) => "Flash the grid when a program rings the bell.",
        vsync: literal(c.vsync) => "Wait for the display refresh before presenting a frame. Disabling this may cause tearing.",
        window_columns: format!("Saved width or {}", crate::window_state::DEFAULT_CELLS.0) => "Set the first window’s width in cells, from 1 to 10000.",
        window_rows: format!("Saved height or {}", crate::window_state::DEFAULT_CELLS.1) => "Set the first window’s height in cells, from 1 to 10000.",
    });
    doc.push_str("\n## scrollback\n\nUse `[scrollback]` instead of the integer form. Per-command limits require [shell integration](configuration.md#shell-integration).\n");
    table!(Scrollback {
        lines: literal(c.scrollback) => "Set the total history size in lines.",
        command_budget: literal(c.command_budget) => "Drop the middle of oversized command output instead of evicting the oldest history first.",
        command_share: literal(c.command_share) => "Set the fraction of history one command may use, greater than 0 and at most 1.",
    });
    doc.push_str("\n## compare_runs\n\nUse `[compare_runs]` instead of the boolean form to customize [output comparison](configuration.md#compare-runs).\n");
    table!(CompareRuns {
        enabled: literal(c.compare_runs) => "Compare successive runs marked by shell integration.",
        default_ignore: literal(true) => "Ignore built-in patterns such as timestamps and process IDs.",
        ignore: literal(&CompareRuns::default().ignore) => "Add regular expressions for text to ignore on each line.",
    });
    doc.push_str("\n## colors\n\nUse quoted `#rgb` or `#rrggbb` strings in `[colors]`. Each shorthand digit is doubled: `#a3f` means `#aa33ff`. These are the defaults without a theme override.\n\n| Key | Color |\n| --- | --- |\n");
    let theme: toml::Table = include_str!("../../../../themes/tokyo-night.toml")
        .parse()
        .unwrap();
    for (key, value) in theme["colors"].as_table().unwrap() {
        writeln!(doc, "| `{key}` | `{value}` |").unwrap();
    }
    doc
}

const REFERENCE: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../../docs/config-reference.md"
);

#[test]
fn config_reference_is_current() {
    assert_eq!(
        std::fs::read_to_string(REFERENCE).unwrap(),
        render(),
        "Regenerate with cargo test -p term-app write_config_reference -- --ignored"
    );
}

#[test]
#[ignore = "writes the checked-in reference"]
fn write_config_reference() {
    std::fs::write(REFERENCE, render()).unwrap();
}
